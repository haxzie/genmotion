/**
 * Embed the watermark artwork as a TS string constant.
 *
 * `watermark.ts` needs the same source whether it runs unbundled via `tsx`
 * (apps/renderer) or gets esbuild-bundled into one file with everything else
 * (apps/desktop's main process, where `import.meta.url`-relative reads would
 * resolve against the *bundle's* location, not this package's). Embedding
 * sidesteps the difference entirely — no asar-unpack, no dist/ copy step, no
 * path math. Re-run this after editing the artwork.
 *
 *   node scripts/generate-watermark.mjs
 */
import path from "node:path";
import fs from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = await fs.readFile(path.join(root, "assets/genmotion-watermark.svg"), "utf8");

const out = `// Generated by scripts/generate-watermark.mjs from assets/genmotion-watermark.svg.
// Do not hand-edit — re-run the script after changing the artwork.
export const WATERMARK_SVG_SOURCE = ${JSON.stringify(source.trim())};
`;

await fs.writeFile(path.join(root, "src/watermark-svg.generated.ts"), out, "utf8");
console.log("wrote src/watermark-svg.generated.ts");
